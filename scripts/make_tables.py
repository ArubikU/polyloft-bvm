#!/usr/bin/env python3
"""Turn bench_runner.py JSON files (one per platform) into the paper's LaTeX tables.

  python scripts/make_tables.py results_*.json --out tables.tex

Every number in the output comes from raw samples in the JSON; nothing is typed by hand.
"""
import argparse, glob, json, os, sys

ORDER = ["fib", "float", "string", "sort", "array", "poly", "closure", "hash",
         "alloc", "macro", "macro_large", "io", "concurrent"]


def tex(s):
    return s.replace("&", r"\&").replace("_", r"\_")


def fmt_ms(x):
    return f"{x:.0f}" if x >= 100 else f"{x:.1f}"


def ratio_cell(e, base):
    r = e.get("ratio_" + base)
    if not r: return "--"
    s = f"{r['ratio']:.2f}"
    if r["ci_hi"] < 1.0: s = r"\mathbf{" + s + "}"          # significantly faster
    return f"${s}\\,[{r['ci_lo']:.2f},{r['ci_hi']:.2f}]$"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("--out", default="tables.tex")
    a = ap.parse_args()
    files = [f for p in a.files for f in glob.glob(p)]
    runs = [(os.path.basename(f), json.load(open(f))) for f in sorted(files)]
    out = []

    # environment table
    out.append("% --- generated by scripts/make_tables.py; do not edit ---")
    out.append("\\begin{tabular}{@{}llllr@{}}\\toprule")
    out.append("Platform & CPU & OS & CPython & $n$ \\\\\\midrule")
    for name, d in runs:
        e = d["env"]
        out.append(f"{tex(name.replace('results_','').replace('.json',''))} & "
                   f"{tex(e['cpu'])} & {tex(e['os'].split('-with')[0][:28])} & "
                   f"{e['python']} & {e['n']} \\\\")
    out.append("\\bottomrule\\end{tabular}\n")

    # per-platform ratio-to-CPython table
    for name, d in runs:
        out.append(f"% ===== {name} : ratio to CPython and to gopher-lua =====")
        out.append("\\begin{tabular}{@{}lrrrrr@{}}\\toprule")
        out.append("Benchmark & CPython (ms) & Interp.\\ (ms) & CV & vs.\\ CPython [95\\% CI] & vs.\\ Lua [95\\% CI] \\\\\\midrule")
        for b in ORDER:
            e = d["results"].get(b)
            if not e or "bvm" not in e: continue
            py = fmt_ms(e["py"]["median"]) if "py" in e else "--"
            out.append(f"{tex(b)} & {py} & {fmt_ms(e['bvm']['median'])} & "
                       f"{e['bvm']['cv']:.0f}\\% & {ratio_cell(e,'py')} & {ratio_cell(e,'lua')} \\\\")
        out.append("\\bottomrule\\end{tabular}\n")

    # cross-platform summary of ratio to CPython
    out.append("% ===== cross-platform summary (ratio to CPython) =====")
    cols = "l" + "r" * len(runs)
    out.append(f"\\begin{{tabular}}{{@{{}}{cols}@{{}}}}\\toprule")
    out.append("Benchmark & " + " & ".join(tex(n.replace("results_", "").replace(".json", "")) for n, _ in runs) + " \\\\\\midrule")
    for b in ORDER:
        cells = []
        for _, d in runs:
            e = d["results"].get(b, {})
            r = e.get("ratio_py")
            cells.append(f"${r['ratio']:.2f}$" if r else "--")
        if any(c != "--" for c in cells):
            out.append(tex(b) + " & " + " & ".join(cells) + " \\\\")
    out.append("\\bottomrule\\end{tabular}")
    open(a.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
